/**
 * Invitations Router
 * Handles creating in-app invitations for existing registered users,
 * listing user/organization invitations, atomic acceptance, and declining.
 */
const express = require('express');
const crypto = require('crypto');
const authMiddleware = require('../middleware/authMiddleware');
const { requirePermission } = require('../middleware/rbacMiddleware');
const { supabase, getUserClient } = require('../config/supabase');
const { ROLES } = require('../constants/permissions');
const { createNotification } = require('../services/notificationService');

const router = express.Router({ mergeParams: true });

const ROLE_LABELS = {
  admin: 'Admin',
  project_manager: 'Project Manager',
  member: 'Member',
  viewer: 'Viewer',
};

/**
 * Helper: Hash a token using SHA-256
 */
const hashToken = (token) => {
  return crypto.createHash('sha256').update(token).digest('hex');
};

/**
 * Helper: Safely look up an existing registered user by their email address
 * Does not expose directory or return arbitrary users to clients.
 */
const findRegisteredUserByEmail = async (email, dbClient) => {
  const norm = email.trim().toLowerCase();

  // 1. Try PostgreSQL RPC lookup_user_by_email
  try {
    const { data: rpcData, error: rpcErr } = await dbClient.rpc('lookup_user_by_email', {
      p_email: norm,
    });
    if (!rpcErr && Array.isArray(rpcData) && rpcData.length > 0 && rpcData[0]?.id) {
      return rpcData[0];
    }
  } catch {
    // RPC not deployed yet, proceed to fallbacks
  }

  // 2. Query public.profiles by email column
  try {
    const { data: profile, error } = await dbClient
      .from('profiles')
      .select('id, full_name, avatar_url, email, username')
      .ilike('email', norm)
      .maybeSingle();

    if (!error && profile && profile.id) {
      return {
        id: profile.id,
        email: profile.email || norm,
        full_name: profile.full_name || norm.split('@')[0],
        avatar_url: profile.avatar_url,
      };
    }
  } catch {
    // Column might not exist yet
  }

  // 3. Fallback: check profiles by username prefix match (generated by Supabase trigger on signup)
  try {
    const usernamePrefix = norm.split('@')[0].toLowerCase().replace(/[^a-z0-9]/g, '');
    if (usernamePrefix.length >= 2) {
      const { data: candidates, error } = await dbClient
        .from('profiles')
        .select('id, full_name, avatar_url, username')
        .ilike('username', `${usernamePrefix}_%`)
        .limit(5);

      if (!error && candidates && candidates.length > 0) {
        return {
          id: candidates[0].id,
          email: norm,
          full_name: candidates[0].full_name || norm.split('@')[0],
          avatar_url: candidates[0].avatar_url,
        };
      }
    }
  } catch {
    // Ignore
  }

  return null;
};

/**
 * POST /api/organizations/:organizationId/invitations
 * Create a direct in-app invitation for an existing registered FlowSync user.
 * Requires members.manage permission (Admin only).
 */
router.post(
  '/organizations/:organizationId/invitations',
  authMiddleware,
  requirePermission('members.manage'),
  async (req, res, next) => {
    try {
      const { organizationId } = req.params;
      const { email, role = 'member' } = req.body;
      const callerId = req.user.id;
      const callerEmail = (req.user.email || '').trim().toLowerCase();
      const dbClient = getUserClient(req.token);

      if (!email || !email.trim()) {
        return res.status(400).json({
          success: false,
          message: 'Email address is required',
        });
      }

      const normalizedEmail = email.trim().toLowerCase();
      const emailRegex = /^[^\s@]+@[^\s@]+\.[^\s@]+$/;
      if (!emailRegex.test(normalizedEmail)) {
        return res.status(400).json({
          success: false,
          message: 'Please provide a valid email address',
        });
      }

      const validRoles = [ROLES.ADMIN, ROLES.PROJECT_MANAGER, ROLES.MEMBER, ROLES.VIEWER];
      if (!validRoles.includes(role)) {
        return res.status(400).json({
          success: false,
          message: `Invalid role specified. Valid roles are: ${validRoles.join(', ')}`,
        });
      }

      // 1. Verify caller has authority to grant the requested role
      if (req.membership.role !== ROLES.ADMIN && role === ROLES.ADMIN) {
        return res.status(403).json({
          success: false,
          message: 'Forbidden: Only organization Admins can invite new administrators',
        });
      }

      // 2. Prevent self-invitation
      if (normalizedEmail === callerEmail) {
        return res.status(400).json({
          success: false,
          message: 'You cannot invite yourself to this organization',
        });
      }

      // 3. Identify the invited user by their registered email (Safe server-side lookup)
      const targetUser = await findRegisteredUserByEmail(normalizedEmail, dbClient);
      if (!targetUser) {
        return res.status(404).json({
          success: false,
          message: `No registered FlowSync account found with email "${normalizedEmail}". Only existing registered users can be invited in-app. Please ask them to register first.`,
          code: 'USER_NOT_REGISTERED',
        });
      }

      if (targetUser.id === callerId) {
        return res.status(400).json({
          success: false,
          message: 'You cannot invite yourself to this organization',
        });
      }

      // 4. Check if the invited user is already a member of this organization
      const { data: existingMember } = await dbClient
        .from('organization_members')
        .select('id, role')
        .eq('organization_id', organizationId)
        .eq('user_id', targetUser.id)
        .maybeSingle();

      if (existingMember) {
        return res.status(409).json({
          success: false,
          message: `The user with email "${normalizedEmail}" is already a member of this organization (${ROLE_LABELS[existingMember.role] || existingMember.role}).`,
        });
      }

      // 5. Check for existing pending invitation for this email or user in this organization
      let existingInviteQuery = dbClient
        .from('organization_invitations')
        .select('id, expires_at, status')
        .eq('organization_id', organizationId)
        .eq('status', 'pending');

      if (targetUser.id) {
        existingInviteQuery = existingInviteQuery.or(
          `email.ilike.${normalizedEmail},invited_user_id.eq.${targetUser.id}`
        );
      } else {
        existingInviteQuery = existingInviteQuery.ilike('email', normalizedEmail);
      }

      const { data: existingInvite } = await existingInviteQuery.maybeSingle();

      if (existingInvite) {
        if (new Date(existingInvite.expires_at) < new Date()) {
          // If expired, update status to expired and allow new invitation
          await dbClient
            .from('organization_invitations')
            .update({ status: 'expired' })
            .eq('id', existingInvite.id);
        } else {
          return res.status(409).json({
            success: false,
            message: `A pending invitation has already been sent to ${normalizedEmail}. You can revoke it before creating a new one.`,
          });
        }
      }

      // 6. Generate cryptographically secure token & hash for fallback link compatibility
      const rawToken = crypto.randomBytes(32).toString('hex');
      const token_hash = hashToken(rawToken);

      // 7-day expiration
      const expiresAt = new Date();
      expiresAt.setDate(expiresAt.getDate() + 7);

      // 7. Insert pending invitation record
      const { data: newInvite, error: insertErr } = await dbClient
        .from('organization_invitations')
        .insert({
          organization_id: organizationId,
          email: normalizedEmail,
          role,
          token_hash,
          invited_by: callerId,
          invited_user_id: targetUser.id,
          status: 'pending',
          expires_at: expiresAt.toISOString(),
        })
        .select('id, organization_id, email, role, status, expires_at, created_at, invited_user_id')
        .single();

      if (insertErr) {
        if (insertErr.code === '23505' || insertErr.message?.includes('unique')) {
          return res.status(409).json({
            success: false,
            message: `A pending invitation already exists for ${normalizedEmail}.`,
          });
        }
        return res.status(400).json({
          success: false,
          message: insertErr.message || 'Failed to create organization invitation',
        });
      }

      // 8. Fetch Organization & Inviter details for the notification
      const { data: orgData } = await dbClient
        .from('organizations')
        .select('name')
        .eq('id', organizationId)
        .maybeSingle();

      const { data: callerProfile } = await dbClient
        .from('profiles')
        .select('full_name')
        .eq('id', callerId)
        .maybeSingle();

      const orgName = orgData?.name || 'Workspace';
      const inviterName =
        callerProfile?.full_name ||
        req.user.user_metadata?.full_name ||
        req.user.email?.split('@')[0] ||
        'An administrator';

      // 9. Dispatch in-app notification to the invited user
      await createNotification({
        dbClient,
        userId: targetUser.id,
        organizationId,
        type: 'organization_invitation_received',
        title: `Invitation to join ${orgName}`,
        message: `${inviterName} invited you to join ${orgName} as ${ROLE_LABELS[role] || role}.`,
        entityType: 'organization_invitation',
        entityId: newInvite.id,
        actorId: callerId,
        metadata: {
          invitation_id: newInvite.id,
          organization_id: organizationId,
          organization_name: orgName,
          role,
          inviter_name: inviterName,
        },
      });

      // 10. Return success response
      res.status(201).json({
        success: true,
        message: `Invitation sent successfully to ${normalizedEmail}. They will receive an in-app notification to accept or decline.`,
        data: {
          id: newInvite.id,
          organizationId: newInvite.organization_id,
          email: newInvite.email,
          role: newInvite.role,
          status: newInvite.status,
          expiresAt: newInvite.expires_at,
          createdAt: newInvite.created_at,
          invitedUserId: targetUser.id,
          recipientName: targetUser.full_name,
          token: rawToken, // Kept for compatibility with fallback links
        },
      });
    } catch (err) {
      next(err);
    }
  }
);

/**
 * GET /api/invitations/my-pending
 * Get all pending, non-expired organization invitations for the authenticated user.
 */
router.get('/invitations/my-pending', authMiddleware, async (req, res, next) => {
  try {
    const userId = req.user.id;
    const userEmail = (req.user.email || '').trim().toLowerCase();
    const dbClient = getUserClient(req.token);

    const { data: invites, error } = await dbClient
      .from('organization_invitations')
      .select(`
        id,
        organization_id,
        email,
        role,
        status,
        expires_at,
        created_at,
        invited_by,
        invited_user_id,
        organizations (
          id,
          name,
          slug,
          logo_url,
          description
        )
      `)
      .eq('status', 'pending')
      .or(`invited_user_id.eq.${userId},email.ilike.${userEmail}`)
      .order('created_at', { ascending: false });

    if (error) {
      return res.status(400).json({
        success: false,
        message: error.message,
      });
    }

    const now = new Date();
    const expiredIds = [];
    const validInvites = [];

    // Fetch inviter profiles
    const inviterIds = [...new Set((invites || []).map((i) => i.invited_by).filter(Boolean))];
    let inviterMap = {};
    if (inviterIds.length > 0) {
      const { data: inviterProfiles } = await dbClient
        .from('profiles')
        .select('id, full_name, avatar_url')
        .in('id', inviterIds);
      if (inviterProfiles) {
        inviterProfiles.forEach((p) => {
          inviterMap[p.id] = p;
        });
      }
    }

    for (const inv of invites || []) {
      if (new Date(inv.expires_at) < now) {
        expiredIds.push(inv.id);
      } else {
        const inviter = inviterMap[inv.invited_by] || null;
        validInvites.push({
          id: inv.id,
          organizationId: inv.organization_id,
          organizationName: inv.organizations?.name || 'Workspace',
          organizationSlug: inv.organizations?.slug,
          organizationLogo: inv.organizations?.logo_url,
          organizationDescription: inv.organizations?.description,
          email: inv.email,
          role: inv.role,
          status: inv.status,
          expiresAt: inv.expires_at,
          createdAt: inv.created_at,
          invitedBy: inv.invited_by,
          inviterName: inviter?.full_name || 'Organization Admin',
          inviterAvatar: inviter?.avatar_url,
        });
      }
    }

    // Auto-update expired in background
    if (expiredIds.length > 0) {
      dbClient
        .from('organization_invitations')
        .update({ status: 'expired' })
        .in('id', expiredIds)
        .then(() => {})
        .catch(() => {});
    }

    res.json({
      success: true,
      data: validInvites,
      count: validInvites.length,
    });
  } catch (err) {
    next(err);
  }
});

/**
 * POST /api/invitations/:idOrToken/accept
 * Accept an organization invitation using the authenticated user's session.
 * Supports both UUID invitation ID (in-app) and 64-character token (fallback link).
 */
router.post('/invitations/:idOrToken/accept', authMiddleware, async (req, res, next) => {
  try {
    const { idOrToken } = req.params;
    const userId = req.user.id;
    const userEmail = (req.user.email || '').trim().toLowerCase();
    const dbClient = getUserClient(req.token);

    if (!idOrToken) {
      return res.status(400).json({
        success: false,
        message: 'Invitation identifier or token is required',
      });
    }

    const isUuid = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i.test(idOrToken);
    const tokenHash = isUuid ? null : hashToken(idOrToken);

    // 1. Try atomic PostgreSQL RPC function if available
    if (isUuid) {
      try {
        const { data: rpcResult, error: rpcErr } = await dbClient.rpc('accept_invitation_by_id_atomic', {
          p_invitation_id: idOrToken,
          p_user_id: userId,
          p_user_email: userEmail,
        });

        if (!rpcErr && rpcResult) {
          if (!rpcResult.success) {
            return res.status(400).json({
              success: false,
              message: rpcResult.error || 'Failed to accept invitation',
            });
          }

          return res.json({
            success: true,
            message: rpcResult.message || 'Invitation accepted successfully',
            data: {
              organizationId: rpcResult.organization_id,
              organizationName: rpcResult.organization_name,
              role: rpcResult.role,
              alreadyMember: rpcResult.already_member,
            },
          });
        }
      } catch {
        // Fall back to direct atomic node logic
      }
    } else {
      try {
        const { data: rpcResult, error: rpcErr } = await dbClient.rpc('accept_invitation_atomic', {
          p_token_hash: tokenHash,
          p_user_id: userId,
          p_user_email: userEmail,
        });

        if (!rpcErr && rpcResult) {
          if (!rpcResult.success) {
            return res.status(400).json({
              success: false,
              message: rpcResult.error || 'Failed to accept invitation',
            });
          }

          return res.json({
            success: true,
            message: rpcResult.message || 'Invitation accepted successfully',
            data: {
              organizationId: rpcResult.organization_id,
              organizationName: rpcResult.organization_name,
              role: rpcResult.role,
              alreadyMember: rpcResult.already_member,
            },
          });
        }
      } catch {
        // Fall back to direct logic
      }
    }

    // 2. Direct atomic Node.js fallback
    let query = dbClient.from('organization_invitations').select('*, organizations(id, name)');
    if (isUuid) {
      query = query.eq('id', idOrToken);
    } else {
      query = query.eq('token_hash', tokenHash);
    }

    const { data: invite, error: findErr } = await query.maybeSingle();

    if (findErr || !invite) {
      return res.status(404).json({
        success: false,
        message: 'Invalid or non-existent invitation.',
      });
    }

    // Verify authenticated user is the intended recipient
    const invitedEmail = (invite.email || '').trim().toLowerCase();
    const isIntendedUser =
      (invite.invited_user_id && invite.invited_user_id === userId) || invitedEmail === userEmail;

    if (!isIntendedUser) {
      return res.status(403).json({
        success: false,
        message: `This invitation was issued to ${invite.email}. You are currently signed in as ${userEmail}. Please sign in with the invited email address to accept.`,
      });
    }

    if (invite.status === 'accepted') {
      return res.status(400).json({
        success: false,
        message: 'This invitation has already been accepted.',
      });
    }

    if (invite.status === 'declined') {
      return res.status(400).json({
        success: false,
        message: 'This invitation was previously declined.',
      });
    }

    if (invite.status === 'revoked') {
      return res.status(400).json({
        success: false,
        message: 'This invitation has been revoked by an administrator.',
      });
    }

    if (invite.status !== 'pending') {
      return res.status(400).json({
        success: false,
        message: 'This invitation is no longer valid.',
      });
    }

    if (new Date(invite.expires_at) < new Date()) {
      await dbClient.from('organization_invitations').update({ status: 'expired' }).eq('id', invite.id);
      return res.status(400).json({
        success: false,
        message: 'This invitation has expired. Please ask an administrator to send a new invitation.',
      });
    }

    // Check if already a member
    const { data: existingMember } = await dbClient
      .from('organization_members')
      .select('id, role')
      .eq('organization_id', invite.organization_id)
      .eq('user_id', userId)
      .maybeSingle();

    if (existingMember) {
      await dbClient
        .from('organization_invitations')
        .update({
          status: 'accepted',
          accepted_by: userId,
          accepted_at: new Date().toISOString(),
        })
        .eq('id', invite.id);

      return res.json({
        success: true,
        message: 'You are already a member of this workspace.',
        data: {
          organizationId: invite.organization_id,
          organizationName: invite.organizations?.name,
          role: existingMember.role,
          alreadyMember: true,
        },
      });
    }

    // Insert membership record
    const { error: memberInsertErr } = await dbClient
      .from('organization_members')
      .insert({
        organization_id: invite.organization_id,
        user_id: userId,
        role: invite.role,
      });

    if (memberInsertErr) {
      return res.status(500).json({
        success: false,
        message: memberInsertErr.message || 'Failed to create organization membership',
      });
    }

    // Mark invitation accepted
    await dbClient
      .from('organization_invitations')
      .update({
        status: 'accepted',
        accepted_by: userId,
        accepted_at: new Date().toISOString(),
      })
      .eq('id', invite.id);

    // Mark related notification as read
    await dbClient
      .from('notifications')
      .update({ is_read: true })
      .eq('user_id', userId)
      .eq('entity_id', invite.id);

    // Notify inviter that invitation was accepted
    if (invite.invited_by && invite.invited_by !== userId) {
      const { data: accepterProfile } = await dbClient
        .from('profiles')
        .select('full_name')
        .eq('id', userId)
        .maybeSingle();

      const accepterName = accepterProfile?.full_name || req.user.email?.split('@')[0] || 'A user';
      const orgName = invite.organizations?.name || 'the workspace';

      createNotification({
        dbClient,
        userId: invite.invited_by,
        organizationId: invite.organization_id,
        type: 'organization_invitation_accepted',
        title: `${accepterName} accepted your invitation`,
        message: `${accepterName} joined ${orgName}.`,
        entityType: 'organization',
        entityId: invite.organization_id,
        actorId: userId,
        metadata: {
          invitationId: invite.id,
          organizationId: invite.organization_id,
        },
      }).catch((e) => console.warn('[INVITATIONS] Notification error:', e.message));
    }

    res.json({
      success: true,
      message: `Joined ${invite.organizations?.name || 'organization'} successfully!`,
      data: {
        organizationId: invite.organization_id,
        organizationName: invite.organizations?.name,
        role: invite.role,
        alreadyMember: false,
      },
    });
  } catch (err) {
    next(err);
  }
});

/**
 * POST /api/invitations/:invitationId/decline
 * Decline a pending in-app invitation.
 */
router.post('/invitations/:invitationId/decline', authMiddleware, async (req, res, next) => {
  try {
    const { invitationId } = req.params;
    const userId = req.user.id;
    const userEmail = (req.user.email || '').trim().toLowerCase();
    const dbClient = getUserClient(req.token);

    if (!invitationId) {
      return res.status(400).json({
        success: false,
        message: 'Invitation ID is required',
      });
    }

    // 1. Try atomic PostgreSQL RPC function if available
    try {
      const { data: rpcResult, error: rpcErr } = await dbClient.rpc('decline_invitation_by_id_atomic', {
        p_invitation_id: invitationId,
        p_user_id: userId,
        p_user_email: userEmail,
      });

      if (!rpcErr && rpcResult) {
        if (!rpcResult.success) {
          return res.status(400).json({
            success: false,
            message: rpcResult.error || 'Failed to decline invitation',
          });
        }

        return res.json({
          success: true,
          message: rpcResult.message || 'Invitation declined successfully',
        });
      }
    } catch {
      // Fall back to direct logic
    }

    // 2. Direct Node.js logic
    const { data: invite, error: findErr } = await dbClient
      .from('organization_invitations')
      .select('id, organization_id, email, status, invited_user_id, invited_by, organizations:organization_id ( name )')
      .eq('id', invitationId)
      .maybeSingle();

    if (findErr || !invite) {
      return res.status(404).json({
        success: false,
        message: 'Invitation not found',
      });
    }

    const invitedEmail = (invite.email || '').trim().toLowerCase();
    const isIntendedUser =
      (invite.invited_user_id && invite.invited_user_id === userId) || invitedEmail === userEmail;

    if (!isIntendedUser) {
      return res.status(403).json({
        success: false,
        message: 'Forbidden: You are not the recipient of this invitation',
      });
    }

    if (invite.status !== 'pending') {
      return res.status(400).json({
        success: false,
        message: `Cannot decline invitation with status "${invite.status}"`,
      });
    }

    // Mark as declined
    const { error: updateErr } = await dbClient
      .from('organization_invitations')
      .update({ status: 'declined' })
      .eq('id', invitationId);

    if (updateErr) {
      return res.status(400).json({
        success: false,
        message: updateErr.message || 'Failed to decline invitation',
      });
    }

    // Mark related notification as read
    await dbClient
      .from('notifications')
      .update({ is_read: true })
      .eq('user_id', userId)
      .eq('entity_id', invitationId);

    // Notify inviter that invitation was declined
    if (invite.invited_by && invite.invited_by !== userId) {
      const { data: declinerProfile } = await dbClient
        .from('profiles')
        .select('full_name')
        .eq('id', userId)
        .maybeSingle();

      const declinerName = declinerProfile?.full_name || req.user.email?.split('@')[0] || 'A user';
      const orgName = invite.organizations?.name || 'the workspace';

      createNotification({
        dbClient,
        userId: invite.invited_by,
        organizationId: invite.organization_id,
        type: 'organization_invitation_declined',
        title: 'Invitation declined',
        message: `${declinerName} declined the invitation to join ${orgName}.`,
        entityType: 'organization',
        entityId: invite.organization_id,
        actorId: userId,
        metadata: {
          invitationId: invite.id,
          organizationId: invite.organization_id,
        },
      }).catch((e) => console.warn('[INVITATIONS] Notification error:', e.message));
    }

    res.json({
      success: true,
      message: 'Invitation declined successfully',
    });
  } catch (err) {
    next(err);
  }
});

